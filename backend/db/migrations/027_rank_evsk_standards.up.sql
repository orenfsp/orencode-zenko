CREATE TABLE rank_evsk_standard (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rank_id bigint NOT NULL REFERENCES rank (id) ON DELETE CASCADE,
    discipline_id bigint NOT NULL REFERENCES discipline (id) ON DELETE CASCADE,
    minimum_place integer,
    minimum_score numeric(12,2),
    valid_from date,
    valid_to date,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT rank_evsk_standard_threshold_check
        CHECK (minimum_place IS NOT NULL OR minimum_score IS NOT NULL),
    CONSTRAINT rank_evsk_standard_place_check
        CHECK (minimum_place IS NULL OR minimum_place > 0),
    CONSTRAINT rank_evsk_standard_dates_check
        CHECK (valid_to IS NULL OR valid_from IS NULL OR valid_to >= valid_from),
    CONSTRAINT rank_evsk_standard_unique_key
        UNIQUE (rank_id, discipline_id)
);
