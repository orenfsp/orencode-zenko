CREATE TABLE judge_category_application (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    judge_user_id bigint NOT NULL REFERENCES "user" (id),
    category_id bigint NOT NULL REFERENCES judge_category (id),
    application_type varchar(20) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'pending',
    submitted_at timestamptz NOT NULL DEFAULT now(),
    reviewed_by_user_id bigint REFERENCES "user" (id),
    reviewed_at timestamptz,
    assigned_at date,
    expires_at date,
    order_number varchar(100),
    rejection_reason varchar(500),
    CONSTRAINT judge_category_application_type_check
        CHECK (application_type IN ('assignment', 'confirmation')),
    CONSTRAINT judge_category_application_status_check
        CHECK (status IN ('pending', 'approved', 'rejected')),
    CONSTRAINT judge_category_application_review_check
        CHECK (
            (status = 'pending' AND reviewed_by_user_id IS NULL AND reviewed_at IS NULL)
            OR (status IN ('approved', 'rejected') AND reviewed_by_user_id IS NOT NULL AND reviewed_at IS NOT NULL)
        ),
    CONSTRAINT judge_category_application_dates_check
        CHECK (expires_at IS NULL OR assigned_at IS NULL OR expires_at >= assigned_at)
);

CREATE UNIQUE INDEX judge_category_application_one_pending_idx
    ON judge_category_application (judge_user_id, category_id, application_type)
    WHERE status = 'pending';

CREATE INDEX judge_category_application_status_submitted_idx
    ON judge_category_application (status, submitted_at, id);

CREATE INDEX judge_category_application_judge_submitted_idx
    ON judge_category_application (judge_user_id, submitted_at DESC, id DESC);

