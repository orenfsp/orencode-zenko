CREATE TABLE rank_application (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    athlete_user_id bigint NOT NULL REFERENCES "user" (id),
    rank_id bigint NOT NULL REFERENCES rank (id),
    discipline_id bigint NOT NULL REFERENCES discipline (id),
    submitted_by_user_id bigint NOT NULL REFERENCES "user" (id),
    status varchar(20) NOT NULL DEFAULT 'pending',
    reviewed_by_user_id bigint REFERENCES "user" (id),
    reviewed_at timestamptz,
    rejection_reason varchar(500),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT rank_application_status_check
        CHECK (status IN ('pending', 'approved', 'rejected', 'withdrawn')),
    CONSTRAINT rank_application_review_check
        CHECK (
            (status = 'pending' AND reviewed_by_user_id IS NULL AND reviewed_at IS NULL)
            OR (status IN ('approved', 'rejected') AND reviewed_by_user_id IS NOT NULL AND reviewed_at IS NOT NULL)
            OR status = 'withdrawn'
        )
);

CREATE UNIQUE INDEX rank_application_one_pending_idx
    ON rank_application (athlete_user_id, rank_id, discipline_id)
    WHERE status = 'pending';

CREATE INDEX rank_application_athlete_created_idx
    ON rank_application (athlete_user_id, created_at DESC);

ALTER TABLE competition_result
    ADD COLUMN awarded_rank_id bigint REFERENCES rank (id);

CREATE UNIQUE INDEX user_rank_discipline_result_id_idx
    ON user_rank_discipline (result_id)
    WHERE result_id IS NOT NULL;

CREATE OR REPLACE FUNCTION apply_rank_application_status() RETURNS TRIGGER AS $$
BEGIN
    IF OLD.status IS NOT DISTINCT FROM NEW.status THEN
        RETURN NEW;
    END IF;

    IF NEW.status = 'approved' THEN
        INSERT INTO user_rank_discipline (
            user_id, rank_id, discipline_id, awarded_at
        )
        SELECT NEW.athlete_user_id, NEW.rank_id, NEW.discipline_id, CURRENT_DATE
        WHERE NOT EXISTS (
            SELECT 1
            FROM user_rank_discipline
            WHERE user_id = NEW.athlete_user_id
              AND rank_id = NEW.rank_id
              AND discipline_id = NEW.discipline_id
              AND result_id IS NULL
        );
    END IF;

    IF NEW.status IN ('approved', 'rejected') THEN
        INSERT INTO notification_outbox (recipient_id, payload)
        VALUES (
            NEW.athlete_user_id,
            jsonb_build_object(
                'type', 'rank_application_status_changed',
                'rank_application_id', NEW.id,
                'status', NEW.status,
                'text', CASE NEW.status
                    WHEN 'approved' THEN 'Ваша заявка на получение разряда одобрена.'
                    ELSE 'Ваша заявка на получение разряда отклонена.'
                END
            )
        );
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_rank_application_status
AFTER UPDATE OF status ON rank_application
FOR EACH ROW EXECUTE FUNCTION apply_rank_application_status();

CREATE OR REPLACE FUNCTION apply_rank_from_competition_result() RETURNS TRIGGER AS $$
DECLARE
    target_user_id bigint;
    target_discipline_id bigint;
BEGIN
    IF NEW.result_status IS DISTINCT FROM 'finished' OR NEW.awarded_rank_id IS NULL THEN
        RETURN NEW;
    END IF;

    SELECT application.athlete_user_id, event.discipline_id
    INTO target_user_id, target_discipline_id
    FROM competition_application AS application
    JOIN competition_event AS event ON event.id = application.event_id
    WHERE application.id = NEW.application_id;

    INSERT INTO user_rank_discipline (
        user_id, rank_id, discipline_id, result_id, awarded_at
    )
    VALUES (
        target_user_id, NEW.awarded_rank_id, target_discipline_id, NEW.id, CURRENT_DATE
    )
    ON CONFLICT (result_id) WHERE result_id IS NOT NULL
    DO UPDATE SET
        rank_id = EXCLUDED.rank_id,
        discipline_id = EXCLUDED.discipline_id,
        awarded_at = EXCLUDED.awarded_at;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_competition_result_rank
AFTER INSERT OR UPDATE OF result_status, awarded_rank_id ON competition_result
FOR EACH ROW EXECUTE FUNCTION apply_rank_from_competition_result();
