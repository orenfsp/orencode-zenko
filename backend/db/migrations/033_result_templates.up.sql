CREATE TABLE discipline_result_template (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discipline_id bigint NOT NULL REFERENCES discipline(id),
    name varchar(200) NOT NULL,
    fields jsonb NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT discipline_result_template_fields_check CHECK (jsonb_typeof(fields) = 'array')
);

ALTER TABLE competition_event_result_sheet
    ADD COLUMN scoring_mode varchar(16) NOT NULL DEFAULT 'algorithmic',
    ADD COLUMN template_id bigint REFERENCES discipline_result_template(id),
    ADD COLUMN template_snapshot jsonb,
    ADD CONSTRAINT result_sheet_scoring_mode_check CHECK (scoring_mode IN ('algorithmic', 'manual')),
    ADD CONSTRAINT result_sheet_template_check CHECK (
        (scoring_mode = 'algorithmic' AND template_id IS NULL AND template_snapshot IS NULL)
        OR (scoring_mode = 'manual' AND template_id IS NOT NULL AND template_snapshot IS NOT NULL
            AND jsonb_typeof(template_snapshot) = 'object')
    );

ALTER TABLE competition_event_result_sheet
    DROP CONSTRAINT competition_event_result_sheet_task_count_check,
    ADD CONSTRAINT competition_event_result_sheet_task_count_check CHECK (
        (scoring_mode = 'algorithmic' AND task_count BETWEEN 1 AND 50)
        OR (scoring_mode = 'manual' AND task_count = 0)
    );

ALTER TABLE competition_event_result_entry
    ADD COLUMN custom_values jsonb NOT NULL DEFAULT '{}'::jsonb,
    ADD CONSTRAINT result_entry_custom_values_check CHECK (jsonb_typeof(custom_values) = 'object');
